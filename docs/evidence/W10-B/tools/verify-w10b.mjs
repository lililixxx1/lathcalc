#!/usr/bin/env node
/**
 * W10-B · 第三源数值核对与门禁汇总
 *
 * 输入（均为公开来源的逐字摘录，见 runs/source-*-extract.txt）:
 *   P1  (GB/T 12716-2011 转载): 5 -> 140.952 mm, 6 -> 167.792 mm (大径 d=D)
 *   S1  (gewinde-normen.de):    5 -> 141.300 mm, 6 -> 168.275 mm (Major Diameter;
 *                               5/6 行为管外径口径)
 *   T3-A(amesweb, ASME B1.20.1): E1 (gaging-plane pitch dia)
 *                               5 -> 5.44929 in, 6 -> 6.50597 in; P = 0.125 in
 *   T3-M(mechtool.cn):          5 -> 140.952 mm, 6 -> 167.792 mm (大径 d=D)
 *
 * 规则（派工单冻结判定规则）:
 *   A 方案 = 第三源有「基面大径」直列，且与两候选之一逐位一致。
 *   B 方案 = 仍错位 / 仅单源 / 无合格第三源 -> 零代码，登记结案。
 *
 * 本脚本只做算术与门禁汇总，判定行由脚本生成，不手填。
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(process.cwd());
const runs = resolve(root, 'docs/evidence/W10-B/runs');

const IN = 25.4; // mm per inch
const P_IN = 0.125; // inch, NPT 5/6: 8 TPI -> P = 1/8 in = 3.175 mm
const CANDIDATES = {
  P1: { '5': 140.952, '6': 167.792 },
  S1: { '5': 141.3, '6': 168.275 },
};
// AmesWeb ASME B1.20.1 chart, column E1 = pitch diameter at gaging plane (inch)
const T3A_E1_IN = { '5': 5.44929, '6': 6.50597 };
// Same source: E0 and basic minor at small end, for source-internal relation check
const T3A_E0_IN = { '5': 5.39073, '6': 6.44609 };
const T3A_MINOR_SMALL_IN = { '5': 5.2907, '6': 6.3461 };
// P1 pitch diameter at gaging plane (mm), for E1 cross-check
const P1_D2 = { '5': 138.412, '6': 165.252 };
// mechtool.cn direct basic major column (mm)
const T3M_MAJOR = { '5': 140.952, '6': 167.792 };

const round3 = (x) => Math.round(x * 1000) / 1000;

const rows = ['5', '6'].map((spec) => {
  const derivedMajor = round3((T3A_E1_IN[spec] + 0.8 * P_IN) * IN);
  const e1MM = round3(T3A_E1_IN[spec] * IN);
  const minorRelation = round3(T3A_E0_IN[spec] - T3A_MINOR_SMALL_IN[spec]);
  return {
    spec,
    e1_in: T3A_E1_IN[spec],
    e1_mm: e1MM,
    p1_d2: P1_D2[spec],
    d2_match: e1MM === P1_D2[spec],
    derived_major: derivedMajor,
    p1_major: CANDIDATES.P1[spec],
    s1_major: CANDIDATES.S1[spec],
    t3m_major: T3M_MAJOR[spec],
    match_p1: derivedMajor === CANDIDATES.P1[spec],
    match_s1: derivedMajor === CANDIDATES.S1[spec],
    e0_minus_minor: minorRelation,
    profile_08p: round3(0.8 * P_IN),
    t3m_match_p1: T3M_MAJOR[spec] === CANDIDATES.P1[spec],
  };
});

const gates = {};
for (const [name, file] of Object.entries({
  lint: 'gate0-lint.txt',
  tsc: 'gate1-tsc.txt',
  vitest: 'gate2-vitest.txt',
  build: 'gate3-build.txt',
})) {
  const text = readFileSync(resolve(runs, file), 'utf8');
  const m = text.match(/REAL_EXIT=(\d+)/);
  gates[name] = m ? Number(m[1]) : null;
}

const vitestText = readFileSync(resolve(runs, 'gate2-vitest.txt'), 'utf8');
const testFiles = (vitestText.match(/Test Files\s+(\d+) passed/) || [])[1] ?? '?';
const tests = (vitestText.match(/Tests\s+(\d+) passed/) || [])[1] ?? '?';

const iso = readFileSync(resolve(runs, 'isolation-check.txt'), 'utf8');
const isoJudgment = (iso.match(/JUDGMENT=(\w+)/) || [])[1] ?? '?';

/**
 * 第三源直列事实（人工检索结论，脚本只记录为输入）:
 * - AmesWeb/ASME B1.20.1: 无「基面大径」列（只有 E1 基面中径），派生值匹配 P1。
 * - mechtool.cn: 有「大径 d=D」列且匹配 P1，但为中文参考站同系转录，权威性不可确认
 *   （派工单上报条件 2），不计为合格独立第三源。
 * - doc88/book118/百度文库: ASME 中文译本镜像（上报条件 2）。
 */
const thirdSourceHasDirectMajorColumn = false;
const thirdSourceIndependentAuthority = false;

const bothMatchP1 = rows.every((r) => r.match_p1);
const bothMatchS1 = rows.every((r) => r.match_s1);
const verdict =
  thirdSourceHasDirectMajorColumn &&
  thirdSourceIndependentAuthority &&
  (bothMatchP1 !== bothMatchS1)
    ? 'A_PLAN'
    : 'B_PLAN';

const lines = [];
lines.push('W10-B · third-source numeric check and gate summary');
lines.push('generated by tools/verify-w10b.mjs (judgment line computed, not hand-filled)');
lines.push('');
for (const r of rows) {
  lines.push(
    `SPEC=${r.spec} T3A_E1_in=${r.e1_in} T3A_E1_mm=${r.e1_mm} P1_d2=${r.p1_d2} D2_MATCH=${r.d2_match}`
  );
  lines.push(
    `SPEC=${r.spec} DERIVED_MAJOR=D=E1+0.8P=${r.derived_major}mm P1=${r.p1_major} S1=${r.s1_major} MATCH_P1=${r.match_p1} MATCH_S1=${r.match_s1}`
  );
  lines.push(
    `SPEC=${r.spec} SRC_INTERNAL_E0_MINUS_SMALL_MINOR=${r.e0_minus_minor} EXPECTED_0.8P=${r.profile_08p}`
  );
  lines.push(
    `SPEC=${r.spec} T3M_MECHTOOL_MAJOR=${r.t3m_major} MATCH_P1=${r.t3m_match_p1}`
  );
}
lines.push('');
lines.push(`THIRD_SOURCE_HAS_DIRECT_MAJOR_COLUMN=${thirdSourceHasDirectMajorColumn}`);
lines.push(`THIRD_SOURCE_INDEPENDENT_AUTHORITY=${thirdSourceIndependentAuthority}`);
lines.push(`GATES lint=${gates.lint} tsc=${gates.tsc} vitest=${gates.vitest} build=${gates.build}`);
lines.push(`VITEST test_files=${testFiles} tests=${tests}`);
lines.push(`ISOLATION=${isoJudgment}`);
lines.push(`VERDICT=${verdict}`);
lines.push(
  `REASON=${
    verdict === 'B_PLAN'
      ? 'no qualifying third source with a direct basic-major-diameter column; derived ASME value matches P1 but is not a published major column; mechtool direct match is same-lineage/unconfirmed authority (report condition 2)'
      : 'third source direct basic-major column matches a candidate'
  }`
);

const out = lines.join('\n') + '\n';
process.stdout.write(out);
